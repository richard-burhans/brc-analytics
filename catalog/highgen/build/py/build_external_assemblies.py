"""Write HighGen's external (non-NCBI) assemblies from the cannabis-genome inventory.

The inventory is data/processed/genome_inventory.json in the cannabis-genome
repository, a generated file (scripts/build_genome_inventory.py there). This
script selects its canonical assemblies that have no NCBI record and writes
catalog/highgen/source/external_assemblies.yml, which is committed and read by
build-catalog.ts. Duplicate records (the Zenodo and Ensembl Plants copies of
NCBI assemblies) are not canonical and are left out.

Usage:
  python3 -m catalog.highgen.build.py.build_external_assemblies \
    --inventory ../cannabis-genome/data/processed/genome_inventory.json
"""

import argparse
import json
import re

import yaml

OUTPUT_PATH = "catalog/highgen/source/external_assemblies.yml"

SOURCE_NAMES = {
    "coge_first_light": "CoGe",
    "gigadb": "GigaDB",
    "ngdc": "NGDC Genome Warehouse",
    "salk": "Salk pangenome (figshare)",
}

LICENSES = {
    "CC BY 4.0": "CC BY 4.0",
    "Creative Commons Attribution 4.0 International": "CC BY 4.0",
    "Creative Commons Zero v1.0 Universal": "CC0 1.0",
}

LEVELS = {
    "chromosome": "Chromosome",
    "chromosome-scale": "Chromosome",
    "scaffolded": "Scaffold",
    "unscaffolded": "Contig",
}


def get_license(license_name):
    """Short licence name; anything unrecognised was never stated as a licence."""
    return LICENSES.get(license_name, "Not stated")


def get_landing_url(row):
    """Landing page; CoGe's inventory link is a search, so use the genome page."""
    match = re.search(r"coge(\d+)$", row["label"])
    if row["id"].startswith("coge_first_light:") and match:
        return f"https://genomevolution.org/coge/GenomeInfo.pl?gid={match.group(1)}"
    return row["links"]["landing"]


def build_entry(row):
    """Convert one inventory row to an external assembly entry."""
    prefix = row["id"].split(":", 1)[0]
    stats = row["stats"]
    n50_mb = stats.get("scaffold_n50_mb")
    scaffold_n50 = stats.get("scaffold_n50")
    if scaffold_n50 is None and n50_mb is not None:
        scaffold_n50 = int(n50_mb * 1_000_000)
    license_name = (row.get("license") or {}).get("name") or ""
    paper = row.get("paper") or {}
    files = row.get("files") or {}
    return {
        "id": row["id"].replace(":", "-"),
        "inventory_id": row["id"],
        "name": row["label"],
        "source": SOURCE_NAMES[prefix],
        "source_set": row["source"],
        "landing_url": get_landing_url(row),
        # Levels may carry a note, e.g. "chromosome (measured: 10 seqs, ...)".
        "level": LEVELS[stats["level"].lower().split()[0]],
        "length": stats["total_bp"],
        "sequence_count": stats.get("seqs"),
        "scaffold_n50": scaffold_n50,
        "n50_rounded_to_mb": stats.get("scaffold_n50") is None and n50_mb is not None,
        "license": get_license(license_name),
        "license_url": (row.get("license") or {}).get("source") or None,
        "citation": paper.get("cite") or None,
        "doi": paper.get("doi") or None,
        "has_gff3": bool(files.get("gff3")),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--inventory", required=True)
    args = parser.parse_args()
    with open(args.inventory) as f:
        inventory = json.load(f)
    canonical = set(inventory["canonical_ids"])
    entries = [
        build_entry(row)
        for row in inventory["assemblies"]
        if row["id"] in canonical and not row["id"].startswith("ncbi:")
    ]
    entries.sort(key=lambda e: e["id"])
    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate external assembly ids")
    header = (
        "# Generated by catalog/highgen/build/py/build_external_assemblies.py"
        " from cannabis-genome's genome_inventory.json; do not edit by hand.\n"
    )
    with open(OUTPUT_PATH, "w") as f:
        f.write(header)
        yaml.safe_dump({"assemblies": entries}, f, sort_keys=False, allow_unicode=True)
    print(f"Wrote {len(entries)} external assemblies to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
